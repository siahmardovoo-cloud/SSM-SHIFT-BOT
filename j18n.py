_LETTER = r"[^\W\d_]"


def _build():
    keys = [k for k, _ in RU]
    seen = set()
    for k in keys:
        if k in seen:
            log.warning("i18n: key duplicated: %r", k)
        seen.add(k)
    mapping = {}
    for k, v in RU:
        mapping.setdefault(k, v)
    parts = []
    for k in sorted(mapping, key=len, reverse=True):
        pre = rf"(?<!{_LETTER})" if re.match(_LETTER, k[0]) else ""
        post = rf"(?!{_LETTER})" if re.match(_LETTER, k[-1]) else ""
        parts.append(pre + re.escape(k) + post)
    return mapping, re.compile("|".join(parts))


_MAP, _RE = _build()
_BQ = re.compile(r"(<blockquote>.*?</blockquote>)", re.S)


def tr(text, lang: str):
    """Матнро ба забони lang мегардонад (ru). Дигар забонҳо — бетағйир."""
    if lang != "ru" or not isinstance(text, str) or not text:
        return text
    parts = _BQ.split(text)  # матни корбарон дар <blockquote> дастнорас мемонад
    for i in range(0, len(parts), 2):
        parts[i] = _RE.sub(lambda m: _MAP[m.group(0)], parts[i])
    return "".join(parts)


def tr_markup(markup, lang: str):
    if lang != "ru" or markup is None or not hasattr(markup, "inline_keyboard"):
        return markup
    rows = []
    for row in markup.inline_keyboard:
        rows.append([b.model_copy(update={"text": tr(b.text, lang)}) for b in row])
    return markup.model_copy(update={"inline_keyboard": rows})


