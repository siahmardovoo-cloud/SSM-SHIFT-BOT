_TEXT_METHODS = {
    "SendMessage", "EditMessageText", "SendPhoto", "SendVideo", "SendDocument",
    "EditMessageCaption", "EditMessageReplyMarkup", "AnswerCallbackQuery", "SendInvoice",
}

